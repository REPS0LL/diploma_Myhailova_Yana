from skimage.metrics import structural_similarity as ssim_metric

# 1. Переводимо обидві моделі в режим валідації
model.eval()
adaptive_model.eval()

# 2. Завантажуємо те саме тестове фото (Індекс 7, як у твоїх основних тестах)
all_files = [f for f in sorted(os.listdir(FACE_DATA_DIR)) if f.lower().endswith(('.png', '.jpg', '.jpeg'))]
test_filename = all_files[7]
