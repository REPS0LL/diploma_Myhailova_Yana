class FaceBlurDataset(Dataset):
    def __init__(self, folder_path, patch_size=256):
        self.folder_path = folder_path
        self.patch_size = patch_size

        # Зчитуємо всі файли з папки зобажень
        self.image_filenames = [f for f in sorted(os.listdir(folder_path)) if f.lower().endswith(('.png', '.jpg', '.jpeg'))]

        # Налаштування розмиття Гаусса
        self.blur_transform = T.GaussianBlur(kernel_size=15, sigma=4.0)
        self.to_tensor = T.ToTensor()

    def __len__(self):
        return len(self.image_filenames)

    def __getitem__(self, idx):
        filename = self.image_filenames[idx]
        img_path = os.path.join(self.folder_path, filename)

        # Завантажуємо оригінальне зобр
        sharp_img = Image.open(img_path).convert('RGB')
        w, h = sharp_img.size

        # Якщо картинка замала хоча б по одній стороні, збільшуємо її, щоб менша сторона була мінімум 256
        if h < self.patch_size or w < self.patch_size:
            if h < w:
                new_h = self.patch_size
                new_w = int(w * (self.patch_size / h))
            else:
                new_w = self.patch_size
                new_h = int(h * (self.patch_size / w))
            sharp_img = sharp_img.resize((new_w, new_h), resample=Image.BICUBIC)

        # Тепер 256x256 гарантовано пройде без помилок
        sharp_patch = T.RandomCrop(self.patch_size)(sharp_img)
        sharp_tensor = self.to_tensor(sharp_patch)

        # Створюємо розмитий вхід для нейромережі
        blur_tensor = self.blur_transform(sharp_tensor)

        return blur_tensor, sharp_tensor

