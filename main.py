# 1. МЕХАНІЗМ АДАПТИВНОЇ УВАГИ (Squeeze-and-Excitation)
class AdaptiveSEBlock(nn.Module):
    def __init__(self, channels, reduction=16):
        super().__init__()
        self.squeeze = nn.AdaptiveAvgPool2d(1)
        self.excitation = nn.Sequential(
            nn.Linear(channels, channels // reduction, bias=False),
            nn.ReLU(inplace=True),
            nn.Linear(channels // reduction, channels, bias=False),
            nn.Sigmoid()
        )

    def forward(self, x):
        b, c, _, _ = x.size()
        y = self.squeeze(x).view(b, c)
        y = self.excitation(y).view(b, c, 1, 1)
        return x * y.expand_as(x)

# 2. АДАПТИВНА ПОДВІЙНА ЗГОРТКА (Базовий будівельний блок)
class AdaptiveDoubleConv(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )
        self.adaptive_se = AdaptiveSEBlock(out_channels)

    def forward(self, x):
        x = self.conv(x)
        x = self.adaptive_se(x) # Мережа сама вирішує, які канали важливіші
        return x

# 3. ГОЛОВНА АРХІТЕКТУРА: ADAPTIVE U-NET (з Resize-Convolution)
class AdaptiveUNet(nn.Module):
    def __init__(self, in_channels=3, out_channels=3):
        super().__init__()

        # ЕНКОДЕР (Шлях стиснення з адаптивними блоками)
        self.inc = AdaptiveDoubleConv(in_channels, 64)
        self.down1 = nn.Sequential(nn.MaxPool2d(2), AdaptiveDoubleConv(64, 128))
        self.down2 = nn.Sequential(nn.MaxPool2d(2), AdaptiveDoubleConv(128, 256))
        self.down3 = nn.Sequential(nn.MaxPool2d(2), AdaptiveDoubleConv(256, 512))

        # ДЕКОДЕР (Шлях розширення з Resize-Convolution)
        self.up1 = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
        self.conv_up1 = AdaptiveDoubleConv(512 + 256, 256)

        self.up2 = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
        self.conv_up2 = AdaptiveDoubleConv(256 + 128, 128)

        self.up3 = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
        self.conv_up3 = AdaptiveDoubleConv(128 + 64, 64)

        # фінальний вихід
        self.outc = nn.Sequential(
            nn.Conv2d(64, out_channels, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        x1 = self.inc(x)
        x2 = self.down1(x1)
        x3 = self.down2(x2)
        x4 = self.down3(x3)

        x = self.up1(x4)
        x = torch.cat([x, x3], dim=1)
        x = self.conv_up1(x)

        x = self.up2(x)
        x = torch.cat([x, x2], dim=1)
        x = self.conv_up2(x)

        x = self.up3(x)
        x = torch.cat([x, x1], dim=1)
        x = self.conv_up3(x)

        return self.outc(x)

