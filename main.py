    weight_canvas[weight_canvas == 0] = 1.0
    output_base /= weight_canvas
    output_adaptive /= weight_canvas

    restored_base_np = np.clip(output_base.permute(1, 2, 0).numpy(), 0.0, 1.0)
    restored_adaptive_np = np.clip(output_adaptive.permute(1, 2, 0).numpy(), 0.0, 1.0)

