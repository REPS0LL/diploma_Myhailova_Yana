W_target, H_target = 512, 512  # Наш фіксований квадрат для чесного А/В тесту
hr_pil = hr_pil.resize((W_target, H_target), resample=Image.BICUBIC)
W, H = hr_pil.size

to_tensor = T.ToTensor()
hr_tensor = to_tensor(hr_pil)
hr_np = np.clip(hr_tensor.permute(1, 2, 0).numpy(), 0.0, 1.0)

